// Emit package-local copies of the reviewed operation contract and thin aliases.
import {readFileSync, writeFileSync, mkdirSync, mkdtempSync, rmSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {join, dirname} from 'node:path';
import {spawnSync} from 'node:child_process';
import {tmpdir} from 'node:os';
const root = dirname(dirname(fileURLToPath(import.meta.url)));
const ops = JSON.parse(readFileSync(join(root, 'api/operations.json')));
const check = process.argv.includes('--check');
function emit(path, data) {
  const file=join(root,path);
  if (check) {
    if (readFileSync(file,'utf8') !== data) throw new Error(`generated contract drift: ${path}`);
  } else writeFileSync(file,data);
}
function format(command, input) {
  const dir=mkdtempSync(join(tmpdir(),'deskcite-format-'));
  try {
    const ext=command==='rustfmt'?'rs':command==='dart'?'dart':'go';
    const source=join(dir,`generated.${ext}`);
    writeFileSync(source,input);
    const args=command==='rustfmt'?[source]:command==='dart'?['format',source]:['-w',source];
    const result=spawnSync(command,args,{encoding:'utf8',timeout:30000});
    if (result.status!==0) throw new Error(result.stderr || `${command} unavailable`);
    return readFileSync(source,'utf8');
  } finally { rmSync(dir,{recursive:true,force:true}); }
}
for (const dir of ['javascript', 'python/deskcite', 'ruby', 'go', 'rust/src']) {
  if (!check) mkdirSync(join(root, dir), {recursive:true});
  emit(join(dir, 'operations.json'), JSON.stringify(ops, null, 2)+'\n');
}
const title = name => name.split('_').map(w => w[0].toUpperCase()+w.slice(1)).join('');
const camel = name => { const t = title(name); return t[0].toLowerCase()+t.slice(1); };
let go = '// Code generated by scripts/generate.mjs; DO NOT EDIT.\npackage deskcite\nimport "context"\n';
let rust = '// Code generated by scripts/generate.mjs.\nimpl Client {\n';
let c = '/* Generated by scripts/generate.mjs. */\n';
let table = '/* Generated by scripts/generate.mjs. */\nstatic const struct operation operations[] = {\n';
for (const [name, spec] of Object.entries(ops)) {
  table += `  {"${name}", "${spec.method}", "${spec.path}", "${spec.kind}"},\n`;
  c += `#define deskcite_${name}(client, args, response) deskcite_call((client), "${name}", (args), (response))\n`;
  if (!['question','document'].includes(name)) {
    const none = spec.kind === 'none';
    go += `func (c *Client) ${title(name)}(ctx context.Context${none?'':', args map[string]any'}) (*Response, error) { return c.Call(ctx, "${name}", ${none?'nil':'args'}) }\n`;
    rust += `pub fn ${name}(&self${none?'':', args: Value'}) -> Result<Response, Error> { self.call("${name}", ${none?'serde_json::json!({})':'args'}) }\n`;
  }
}
emit('go/operations.go',format('gofmt',go));
emit('rust/src/operations.rs',format('rustfmt',rust+'}\n'));
emit('c/operations.h',c);
emit('c/operations.inc',table+'};\n');
// Dart embeds the contract and typed aliases in one generated part file; the
// hand-written Client provides call/question/document/events in deskcite.dart.
let dart = "// Code generated by scripts/generate.mjs; DO NOT EDIT.\npart of 'deskcite.dart';\n\nconst Map<String, Map<String, String>> operations = {\n";
for (const [name, spec] of Object.entries(ops)) {
  dart += `  '${name}': {'path': '${spec.path}', 'method': '${spec.method}', 'kind': '${spec.kind}'},\n`;
}
dart += '};\n\nextension Operations on Client {\n';
for (const [name, spec] of Object.entries(ops)) {
  if (['question','document'].includes(name)) continue;
  const none = spec.kind === 'none';
  dart += `Future<Response> ${camel(name)}(${none?'':'Map<String, dynamic> args'}) => call('${name}'${none?'':', args'});\n`;
}
dart += '}\n';
if (!check) mkdirSync(join(root, 'dart/lib'), {recursive:true});
emit('dart/lib/operations.dart', format('dart', dart));
